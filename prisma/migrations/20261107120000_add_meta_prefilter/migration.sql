CREATE TABLE `MetaPrefilterRun` (
  `id` VARCHAR(36) NOT NULL,
  `shopeeAccountId` INTEGER NOT NULL,
  `activeShopeeAccountId` INTEGER NULL,
  `businessDate` DATE NOT NULL,
  `slot` VARCHAR(8) NOT NULL,
  `revision` INTEGER NOT NULL,
  `requestedAt` DATETIME(3) NOT NULL,
  `finishedAt` DATETIME(3) NULL,
  `status` VARCHAR(32) NOT NULL DEFAULT 'RUNNING',
  `scope` JSON NOT NULL,
  `cursor` JSON NOT NULL,
  `skipped` JSON NOT NULL,
  `pages` INTEGER NOT NULL DEFAULT 0,
  `generation` INTEGER NOT NULL DEFAULT 0,
  `usagePercent` INTEGER NOT NULL DEFAULT 0,
  `leaseOwner` VARCHAR(64) NULL,
  `leaseExpiresAt` DATETIME(3) NULL,
  `error` VARCHAR(300) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `MetaPrefilterRun_activeShopeeAccountId_key` (`activeShopeeAccountId`),
  UNIQUE INDEX `MetaPrefilterRun_revision_key` (`shopeeAccountId`, `businessDate`, `slot`, `revision`),
  INDEX `MetaPrefilterRun_snapshot_idx` (`shopeeAccountId`, `businessDate`, `slot`, `status`, `revision`),
  CONSTRAINT `MetaPrefilterRun_shopeeAccountId_fkey` FOREIGN KEY (`shopeeAccountId`) REFERENCES `ShopeeAccount` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `MetaPrefilterRow` (
  `id` VARCHAR(36) NOT NULL,
  `runId` VARCHAR(36) NOT NULL,
  `metaCampaignId` VARCHAR(64) NOT NULL,
  `metaAccountId` INTEGER NOT NULL,
  `accountId` VARCHAR(64) NOT NULL,
  `wlName` VARCHAR(191) NOT NULL,
  `campaignName` VARCHAR(1024) NOT NULL,
  `configuredStatus` VARCHAR(50) NULL,
  `effectiveStatus` VARCHAR(50) NULL,
  `spend` DECIMAL(24,6) NULL,
  `clicks` BIGINT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `MetaPrefilterRow_runId_metaCampaignId_key` (`runId`, `metaCampaignId`),
  INDEX `MetaPrefilterRow_runId_metaAccountId_idx` (`runId`, `metaAccountId`),
  CONSTRAINT `MetaPrefilterRow_runId_fkey` FOREIGN KEY (`runId`) REFERENCES `MetaPrefilterRun` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
